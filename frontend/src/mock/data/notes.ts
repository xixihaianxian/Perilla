export function createMockNotes(): Note[] {
  const now = new Date().toISOString()
  const notes: Note[] = []

  for (let i = 0; i < 220; i++) {
    const author = randomItem(mockUsers)
    const noteTitles = NOTE_TITLES
    const title = noteTitles[i % noteTitles.length]
    const content = NOTE_CONTENTS[i % NOTE_CONTENTS.length]
    const mediaCount = randomInt(1, 9)
    const coverImage = randomItem(allImages)

    const media: NoteMedia[] = Array.from({ length: mediaCount }, (_, mIndex) => ({
      id: generateId('media'),
      note_id: '', // Will be set after ID generation
      url: mIndex === 0 ? coverImage : randomItem(allImages),
      thumbnail_url: '', // Will match url for simplicity
      width: 640,
      height: randomItem([480, 640, 800, 960]),
      sort_order: mIndex,
      created_at: randomDate(300),
    }))

    const noteTags = randomSubset(mockTags, 1, 5)
    const noteTopics = randomSubset(mockTopics, 0, 3)

    const note: Note = {
      id: generateId('note'),
      user_id: author.id,
      title,
      content,
      cover_image: coverImage,
      status: 'published',
      view_count: randomInt(100, 50000),
      like_count: randomInt(10, 5000),
      comment_count: 0, // Will be updated after comments generated
      favorite_count: randomInt(5, 2000),
      share_count: randomInt(1, 500),
      is_liked: false,
      is_favorited: false,
      author,
      media: media.map((m) => ({ ...m, note_id: '', thumbnail_url: m.url })),
      tags: noteTags,
      topics: noteTopics,
      created_at: randomDate(300),
      updated_at: now,
    }

    // Set note_id in media
    note.media = note.media.map((m) => ({ ...m, note_id: note.id }))

    notes.push(note)
  }

  // Update user note counts
  mockUsers.forEach((user) => {
    user.note_count = notes.filter((n) => n.user_id === user.id).length
  })

  return notes
}

export const mockNotes: Note[] = createMockNotes()
